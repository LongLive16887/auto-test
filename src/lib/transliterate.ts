export const latinToCyrillic = (html: string): string =>
  html.replace(/(<[^>]*>)|([^<]+)/g, (_m, tag, content) => {
    if (tag) return tag;

    let result = content;

    // Нормализуем все варианты апострофов
    result = result.replace(/[ʻʼ‘’`]/g, "'");

    // Узбекские правила
    result = result
      .replace(/\bYe/g, "Е")
      .replace(/\bye/g, "е")
      .replace(/\bYE/g, "Е")

      .replace(/\bE/g, "Э")
      .replace(/\be/g, "э");

    for (const [from, to] of LAT_TO_CYR) {
      result = result.replaceAll(from, to);
    }

    return result;
  });